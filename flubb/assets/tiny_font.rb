# What the pen advances by, in whole pixels. advanceX is 12.4 fixed-point and
# the firmware snaps it per glyph with round-to-nearest (fp4::toPixel), so this
# rounds per glyph too rather than summing and rounding once.
#
# Only U+0020..U+007E. toybox_10Intervals starts {0x20, 0x7E, 0x0}, so ASCII
# indexes the array directly; above that the intervals have gaps and the offset
# arithmetic no longer holds. A codepoint with no glyph advances 0 on the
# device as well, so 0 is faithful rather than a fudge. The guard also stops a
# control character indexing backwards off the end of a Ruby array.
def tiny_font_advance(letter)
  index = letter.ord - 0x20
  return 0 unless index.between?(0, 0x7E - 0x20)
  (TINY_FONT_DATA[index][2] + 8) >> 4
end

# This cut ships no kerning data at all, so the advances simply sum.
def tiny_font_width(text)
  text.chars.sum { |letter| tiny_font_advance(letter) }
end
